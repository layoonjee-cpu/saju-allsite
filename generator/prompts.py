def _get_month_info(year: int, month: int) -> dict:
    """해당 월의 간지 정보 (간단 구현)"""
    heavenly_stems = ["갑", "을", "병", "정", "무", "기", "경", "신", "임", "계"]
    earthly_branches = ["자", "축", "인", "묘", "진", "사", "오", "미", "신", "유", "술", "해"]
    stem_idx = (year * 12 + month - 1) % 10
    branch_idx = (month - 1) % 12
    return {
        "year": year,
        "month": month,
        "stem": heavenly_stems[stem_idx],
        "branch": earthly_branches[branch_idx],
        "month_name": f"{year}년 {month}월",
    }


def part09_month(name: str, saju_context: str, year: int, month: int) -> str:
    info = _get_month_info(year, month)
    korean_months = ["1월", "2월", "3월", "4월", "5월", "6월",
                     "7월", "8월", "9월", "10월", "11월", "12월"]
    chapter_num = month
    return _base_prompt(
        f"PART 09-{chapter_num}. {info['year']}년 {korean_months[month-1]} 운세 ({info['stem']}{info['branch']}월)",
        saju_context, name, 1200, 5,
        f"""[필수 포함 내용 — 반드시 모두 포함]
1. {info['year']}년 {korean_months[month-1]} ({info['stem']}{info['branch']}월) 천간·지지·십성 분석표 (표 형식으로)
2. 이 달 종합 흐름 (4~5문장)
3. ★ 재물운 (단락 1개 이상 — 구체적 수입·지출 흐름과 행동 조언 포함)
4. 직업·일운
5. 인간관계운
6. 건강운
7. 이 달의 핵심 키워드 3개
8. 이 달 하면 좋을 일 / 피할 일 (각 2~3가지)

[반복 금지] 이전 월과 다른 표현·키워드·상황으로 차별화할 것"""
    )


