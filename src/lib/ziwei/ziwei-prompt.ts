// ── 챕터별 프롬프트 빌더 ──────────────────────────────────────────────────

export function buildZiweiChapterPrompt(
  sectionNum: number,
  pan: ZiweiPan,
  input: { name?: string | null; gender?: string; birth_date?: string | null }
): { system: string; user: string } {
  const nameRef = input.name?.trim() ? `${input.name.trim()}님` : "당신";
  const currentYear = new Date().getFullYear();
  const birthYear = input.birth_date ? parseInt(input.birth_date.split("-")[0], 10) : 1990;
  const currentAge = currentYear - birthYear + 1;

  // 섹션별 필요한 궁 데이터만 포함 (사주 혼동 방지 + 토큰 절약)
  const panContext = formatZiweiForChapter(pan, sectionNum, input.name?.trim() ?? null);
  const decadalContext = formatDecadals(pan, currentAge);
  const base = `${panContext}\n${decadalContext}\n\n`;

  const user = buildChapterUser(sectionNum, nameRef, base, decadalContext, currentYear, currentAge);
  return { system: ZIWEI_SYSTEM, user };
}

