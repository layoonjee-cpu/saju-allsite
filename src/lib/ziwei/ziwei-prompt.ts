export type ZiweiPromptInput = {
  pan: ZiweiPan;
  name?: string | null;
  birthDate?: string;
  gender?: "male" | "female";
  currentYear?: number;
};

export function buildZiweiChapterPrompt(
  sectionNum: number,
  pan: ZiweiPan,
  input: { name?: string | null; gender?: string; birth_date?: string | null }
): { system: string; user: string } {
  const nameRef = input.name?.trim() ? `${input.name.trim()}님` : "당신";
  const currentYear = new Date().getFullYear();
  const birthYear = input.birth_date ? parseInt(input.birth_date.split("-")[0], 10) : 1990;
  const currentAge = currentYear - birthYear + 1;

  const panContext = formatZiweiForLLM(pan, input.name?.trim() ?? null);
  const decadalContext = formatDecadals(pan, currentAge);

  const chapterUser = buildChapterUser(sectionNum, nameRef, panContext, decadalContext, currentYear, currentAge, input.birth_date ?? "");

  return { system: ZIWEI_SYSTEM, user: chapterUser };
}

